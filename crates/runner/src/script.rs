//! Job script generation.

/// POSIX single-quote: `it's` → `'it'\''s'`.
pub fn shell_quote(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('\'');
    for c in s.chars() {
        if c == '\'' {
            out.push_str("'\\''");
        } else {
            out.push(c);
        }
    }
    out.push('\'');
    out
}

/// What a command looks like in the log: the first line, plus a note when
/// there is more (GitLab prints the same).
fn display_command(cmd: &str) -> String {
    let trimmed = cmd.trim_end_matches('\n');
    match trimmed.split_once('\n') {
        Some((first, _)) => format!("{first} # collapsed multi-line command"),
        None => trimmed.to_string(),
    }
}

/// A script that stops at the first failing command (`set -e`, plus
/// `pipefail` where the shell has it) and echoes each command in bold green
/// as `$ cmd` before running it.
pub fn generate(commands: &[String], project_dir: &str) -> String {
    let mut s = String::new();
    s.push_str("# generated by rust-afariano-runner\n");
    // `set -o pipefail` in a shell without it is a fatal special-builtin error,
    // so probe in a subshell first.
    s.push_str("if (set -o pipefail) 2>/dev/null; then set -o pipefail; fi\n");
    s.push_str("set -e\n");
    s.push_str(&format!("cd {}\n", shell_quote(project_dir)));
    for cmd in commands {
        if cmd.trim().is_empty() {
            continue;
        }
        s.push_str(&format!("printf '\\033[32;1m$ %s\\033[0;m\\n' {}\n", shell_quote(&display_command(cmd))));
        s.push_str(cmd.trim_end_matches('\n'));
        s.push('\n');
    }
    s
}

/// `sh -c` program that runs `$0` with bash when the image has it, else sh —
/// GitLab's shell detection.
pub const DETECT_SHELL: &str = "if [ -x /usr/local/bin/bash ]; then exec /usr/local/bin/bash \"$0\"; \
elif [ -x /usr/bin/bash ]; then exec /usr/bin/bash \"$0\"; \
elif [ -x /bin/bash ]; then exec /bin/bash \"$0\"; \
else exec sh \"$0\"; fi";

#[cfg(test)]
mod tests {
    use super::*;
    use std::process::Command;

    #[test]
    fn quote_basic() {
        assert_eq!(shell_quote("abc"), "'abc'");
        assert_eq!(shell_quote("it's"), "'it'\\''s'");
        assert_eq!(shell_quote(""), "''");
        assert_eq!(shell_quote("$HOME `x` \"q\""), "'$HOME `x` \"q\"'");
    }

    #[test]
    fn display_multiline() {
        assert_eq!(display_command("echo a\necho b\n"), "echo a # collapsed multi-line command");
        assert_eq!(display_command("echo a\n"), "echo a");
    }

    fn run_sh(shell: &str, script: &str) -> (i32, String) {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("s.sh");
        std::fs::write(&path, script).unwrap();
        let out = Command::new(shell).arg(&path).output().unwrap();
        (out.status.code().unwrap_or(-1), String::from_utf8_lossy(&out.stdout).into_owned())
    }

    #[test]
    fn script_echoes_and_runs_with_tricky_quoting() {
        let dir = tempfile::tempdir().unwrap();
        let cmds = vec!["echo \"it's $((1+1))\"".to_string(), "printf '%s\\n' 'a%sb'".to_string()];
        let script = generate(&cmds, dir.path().to_str().unwrap());
        let (code, out) = run_sh("sh", &script);
        assert_eq!(code, 0, "{out}");
        assert!(out.contains("\x1b[32;1m$ echo \"it's $((1+1))\"\x1b[0;m\n"), "{out:?}");
        assert!(out.contains("it's 2\n"));
        assert!(out.contains("\x1b[32;1m$ printf '%s\\n' 'a%sb'\x1b[0;m\n"), "{out:?}");
        assert!(out.contains("a%sb\n"));
    }

    #[test]
    fn script_stops_at_first_failure() {
        let dir = tempfile::tempdir().unwrap();
        let cmds = vec![
            "echo one".to_string(),
            "false || echo tolerated".to_string(),
            "sh -c 'exit 3'".to_string(),
            "echo never".to_string(),
        ];
        let script = generate(&cmds, dir.path().to_str().unwrap());
        let (code, out) = run_sh("sh", &script);
        assert_eq!(code, 3);
        assert!(out.contains("one\n"));
        assert!(out.contains("tolerated\n"));
        assert!(!out.contains("never\n"));
    }

    #[test]
    fn pipefail_where_supported() {
        let dir = tempfile::tempdir().unwrap();
        let cmds = vec!["false | cat".to_string(), "echo after".to_string()];
        let script = generate(&cmds, dir.path().to_str().unwrap());
        // bash has pipefail: the pipeline fails.
        let (code, out) = run_sh("bash", &script);
        assert_ne!(code, 0);
        assert!(!out.contains("after\n"));
    }

    #[test]
    fn multiline_command_runs_whole() {
        let dir = tempfile::tempdir().unwrap();
        let cmds = vec!["for i in 1 2; do\n  echo n$i\ndone\n".to_string()];
        let script = generate(&cmds, dir.path().to_str().unwrap());
        let (code, out) = run_sh("sh", &script);
        assert_eq!(code, 0);
        assert!(out.contains("collapsed multi-line command"));
        assert!(out.contains("n1\nn2\n"));
    }
}
